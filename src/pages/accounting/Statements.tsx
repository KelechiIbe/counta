// Financial statements under IFRS (or IFRS for SMEs): financial position, profit or loss, changes in equity, cash flows and
// the notes, each with last year beside it. Exported one at a time or as one signed-off set.
import { useState } from 'react';
import { useQueryClient } from '@tanstack/react-query';
import { useInventory, useSession } from '../../state/session';
import { rpc } from '../../lib/supabase';
import { today, yearStart, type Report } from '../../lib/api';
import { areport, periodLabel, prepRows } from '../../lib/accounting';
import { Pills } from '../../components/ui';
import { ExportMenu, PeriodBar, ReportPanel, checkLines, useMeta, type Period } from '../../components/Books';

const SET = ['sofp', 'sopl', 'soce', 'cash_flow', 'notes'] as const;
type Id = (typeof SET)[number];

export default function Statements() {
  const { data: inv } = useInventory();
  const { orgId } = useSession();
  const qc = useQueryClient();
  const [id, setId] = useState<Id>('sofp');
  const [period, setPeriod] = useState<Period>(() => ({ from: yearStart(today(), inv?.org.fiscal_year_start || 1), to: today() }));
  const meta = useMeta();
  if (!inv) return null;
  async function fullSet() {
    const reports = await Promise.all(SET.map((r) => qc.fetchQuery({
      queryKey: ['report', r, areport(r).period === 'asAt' ? null : period.from, period.to, '{}', orgId],
      queryFn: () => rpc<Report>('accounting_report', { p_org: orgId, p_report: r, p_from: areport(r).period === 'asAt' ? null : period.from, p_to: period.to, p_options: {} }),
    })));
    return reports.map((rep, i) => {
      const def = areport(SET[i]);
      return { meta: meta(def.title, def.period === 'asAt' ? periodLabel(null, period.to) : periodLabel(period.from, period.to)), cols: def.cols(rep.extra), rows: prepRows(def, rep.rows),
        extra: checkLines(def.id, rep.extra).map((c) => c.text) };
    });
  }
  const framework = inv.org.reporting_framework === 'ifrs_sme' ? 'IFRS for SMEs' : 'IFRS Accounting Standards';
  return (
    <div className="container">
      <div className="row wrap" style={{ justifyContent: 'space-between', gap: 10 }}>
        <PeriodBar value={period} onChange={setPeriod} />
        <ExportMenu name={`${inv.org.name} financial statements ${period.to}`} sheets={fullSet}
          cover={meta('Financial statements', `For the period ${periodLabel(period.from, period.to)}`, `Prepared under ${framework} as adopted by the Financial Reporting Council of Nigeria. Generated by Counta from the books; review and approval by the directors is required before issue.`)} />
      </div>
      <Pills value={id} onChange={setId} options={SET.map((s) => ({ id: s, label: areport(s).title.replace('Statement of ', '').replace(/^\w/, (c) => c.toUpperCase()) }))} />
      <ReportPanel id={id} period={period} />
    </div>
  );
}
