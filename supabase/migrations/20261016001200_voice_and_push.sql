-- Rows created while the sample business is being generated stay quiet: that business was
-- created in the current transaction.
create or replace function private.quiet(p_org uuid) returns boolean
language sql stable security definer set search_path = public, private as $$
  select exists (select 1 from orgs o where o.id = p_org and o.is_sample and o.created_at >= now() - interval '1 second')
$$;

create or replace function private.notify(p_org uuid, p_user uuid, p_kind text, p_title text, p_body text, p_url text, p_tag text default null)
returns void
language plpgsql security definer set search_path = public, private as $$
begin
  if p_user is null or private.quiet(p_org) then return; end if;
  if p_tag is not null and exists (
    select 1 from notifications where user_id = p_user and tag = p_tag and created_at > now() - interval '10 minutes') then
    return;
  end if;
  insert into notifications (org_id, user_id, kind, title, body, url, tag)
  values (p_org, p_user, p_kind, left(p_title, 120), left(coalesce(p_body, ''), 300), coalesce(p_url, '/'), p_tag);
end $$;

-- Everyone in the business holding p_perm ('owner' means owners only), optionally limited to one
-- branch (owners and people without a home branch always count) and leaving out one member.
create or replace function private.notify_perm(p_org uuid, p_perm text, p_kind text, p_title text, p_body text, p_url text,
  p_tag text default null, p_except uuid default null, p_location uuid default null)
returns void
language plpgsql security definer set search_path = public, private as $$
declare m public.members;
begin
  if private.quiet(p_org) then return; end if;
  for m in select * from members where org_id = p_org and status = 'active' and user_id is not null loop
    if (p_except is null or m.id <> p_except)
       and private.perm_of(m, p_perm)
       and (p_location is null or m.location_id is null or m.location_id = p_location or m.role = 'owner') then
      perform private.notify(p_org, m.user_id, p_kind, p_title, p_body, p_url, p_tag);
    end if;
  end loop;
end $$;

create or replace function private.push_notification() returns trigger
