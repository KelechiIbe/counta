-- Counta · phone calls through ElevenLabs agents, and push notifications
--
-- Voice calls. An owner (or anyone who can approve purchase orders) can have Martina phone a
-- vendor to place a purchase order, and an owner or manager can have her phone a team member
-- about something waiting in the app. The database prepares each call (permission check, the
-- facts Martina reads out, the number in +234 form); the `voice` edge function places it through
-- ElevenLabs and writes back what the vendor or team member said. A pg_cron job asks the edge
-- function to collect results for calls still in progress, so outcomes arrive without anyone
-- keeping the page open.
--
-- Push. Devices register a Web Push subscription. Business events (a count waiting for approval,
-- an invoice read and ready to confirm, a transfer on its way, a price check, a call outcome)
-- insert rows into `notifications`; a trigger hands each row to the `push` edge function through
-- pg_net. The edge functions authenticate these database calls with PUSH_HOOK_SECRET from Vault.

create extension if not exists pg_net with schema extensions;

-- ---------------------------------------------------------------------------
-- 1. Server-side settings and the hook into edge functions
-- ---------------------------------------------------------------------------
create table if not exists private.config (key text primary key, value text not null);
insert into private.config (key, value)
values ('functions_url', 'https://krtqqhndmncarwusukrw.supabase.co/functions/v1')
on conflict (key) do nothing;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'PUSH_HOOK_SECRET') then
    perform vault.create_secret(encode(extensions.gen_random_bytes(32), 'hex'), 'PUSH_HOOK_SECRET',
      'Shared secret between database hooks and the push and voice edge functions');
  end if;
end $$;

create or replace function private.call_function(p_name text, p_body jsonb) returns bigint
language plpgsql security definer set search_path = public, private as $$
declare v_url text; v_secret text;
begin
  select value into v_url from private.config where key = 'functions_url';
  select decrypted_secret into v_secret from vault.decrypted_secrets where name = 'PUSH_HOOK_SECRET' order by created_at desc limit 1;
  if v_url is null or v_secret is null then return null; end if;
  return net.http_post(
    url := v_url || '/' || p_name,
    body := p_body,
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-counta-hook', v_secret),
    timeout_milliseconds := 15000);
end $$;

-- Lets edge functions store a key they generate themselves (the VAPID pair), once.
create or replace function public.app_secret_init(p_name text, p_value text) returns boolean
language plpgsql security definer set search_path = public, vault as $$
begin
  if p_name not in ('VAPID_PUBLIC_KEY', 'VAPID_PRIVATE_KEY') then raise exception 'Not allowed.'; end if;
  if exists (select 1 from vault.secrets where name = p_name) then return false; end if;
  perform vault.create_secret(p_value, p_name, 'Generated by the push edge function');
  return true;
end $$;

-- Nigerian numbers in +234 form; other numbers must already carry a country code.
create or replace function private.e164(p_phone text) returns text
language plpgsql immutable set search_path = public, private as $$
declare d text := regexp_replace(coalesce(p_phone, ''), '[^0-9+]', '', 'g');
begin
  if d = '' then return null; end if;
  if left(d, 1) = '+' then d := '+' || regexp_replace(d, '[^0-9]', '', 'g');
  elsif left(d, 3) = '234' then d := '+' || d;
  elsif left(d, 1) = '0' and length(d) = 11 then d := '+234' || substr(d, 2);
  elsif length(d) = 10 and left(d, 1) in ('7', '8', '9') then d := '+234' || d;
  else return null; end if;
  if length(d) < 9 or length(d) > 16 then return null; end if;
  return d;
end $$;

