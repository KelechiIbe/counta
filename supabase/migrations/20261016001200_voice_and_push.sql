create or replace function private.on_count_status() returns trigger
language plpgsql security definer set search_path = public, private as $$
declare v_loc text; v_n int; v_counter text;
begin
  if new.status is not distinct from old.status then return new; end if;
  select name into v_loc from locations where id = new.location_id;
  if new.status in ('awaiting_approval', 'awaiting_reasons') then
    select count(*) into v_n from count_lines where session_id = new.id and counted is not null and counted <> expected;
    select display_name into v_counter from members where id = new.assignee_id;
    perform private.notify_perm(new.org_id, 'approve_adjustments', 'count_submitted',
      'Count ' || new.ref || ' is ready for you',
      new.area || ' at ' || coalesce(v_loc, 'the branch') || ' · ' || case when v_n = 0 then 'no differences' else v_n || ' difference' || case when v_n > 1 then 's' else '' end || ' to review' end
        || coalesce(' · counted by ' || split_part(v_counter, ' ', 1), ''),
      '/inventory/counts?open=' || new.id, 'count:' || new.id, new.assignee_id);
  elsif new.status = 'open' and old.status in ('awaiting_approval', 'awaiting_reasons') then
    perform private.notify(new.org_id, (select user_id from members where id = new.assignee_id), 'count_rejected',
      'Please recount ' || new.area, 'The count ' || new.ref || ' at ' || coalesce(v_loc, 'your branch') || ' was sent back for a recount.',
      '/m/count/' || new.id, 'count:' || new.id);
  end if;
  return new;
end $$;
create trigger count_sessions_notify after update of status on public.count_sessions
  for each row execute function private.on_count_status();

create or replace function private.on_receipt_read() returns trigger
language plpgsql security definer set search_path = public, private as $$
declare v_doubt int; v_lines int; v_title text; v_body text; v_creator uuid;
begin
  if not (old.status = 'reading' and new.status = 'needs_review') then return new; end if;
  select count(*), count(*) filter (where not confirmed) into v_lines, v_doubt from receipt_lines where receipt_id = new.id;
  v_title := new.ref || ' from ' || coalesce(nullif(new.vendor_name, ''), 'a vendor') || ' is ready to confirm';
  v_body := case when new.ai_error is not null then 'Reading needs a hand: ' || left(new.ai_error, 120)
                 when v_lines = 0 then 'No lines were read. Add them by hand.'
                 when v_doubt = 0 then v_lines || ' line' || case when v_lines > 1 then 's' else '' end || ' read. Check and post.'
                 else v_doubt || ' of ' || v_lines || ' lines need a look before posting.' end;
  select user_id into v_creator from members where id = new.created_by;
  perform private.notify(new.org_id, v_creator, 'receipt_ready', v_title, v_body, '/inventory/receive?open=' || new.id, 'receipt:' || new.id);
  perform private.notify_perm(new.org_id, 'owner', 'receipt_ready', v_title, v_body, '/inventory/receive?open=' || new.id, 'receipt:' || new.id, new.created_by);
  return new;
end $$;
create trigger receipts_notify after update of status on public.receipts
  for each row execute function private.on_receipt_read();

create or replace function private.on_transfer() returns trigger
language plpgsql security definer set search_path = public, private as $$
declare it public.items; v_from text; v_to text;
begin
  select * into it from items where id = new.item_id;
  select name into v_from from locations where id = new.from_location_id;
  select name into v_to from locations where id = new.to_location_id;
  if tg_op = 'INSERT' and new.status = 'in_transit' then
    perform private.notify_perm(new.org_id, 'receive_stock', 'transfer_sent',
      new.ref || ' is on its way to ' || coalesce(v_to, 'your branch'),
      private.fmt_qty(new.qty) || ' ' || coalesce(it.selling_unit, 'units') || ' of ' || coalesce(it.name, 'stock') || ' from ' || coalesce(v_from, 'another branch') || '. Confirm it when it arrives.',
      '/m', 'transfer:' || new.id, new.created_by, new.to_location_id);
  elsif tg_op = 'UPDATE' and new.status = 'received' and old.status = 'in_transit' then
    perform private.notify(new.org_id, (select user_id from members where id = new.created_by), 'transfer_received',
      new.ref || ' arrived at ' || coalesce(v_to, 'the branch'),
      private.fmt_qty(new.qty) || ' ' || coalesce(it.selling_unit, 'units') || ' of ' || coalesce(it.name, 'stock') || ' is now in their stock.',
      '/inventory/locations', 'transfer:' || new.id);
  end if;
  return new;
end $$;
create trigger transfers_notify after insert or update of status on public.transfers
  for each row execute function private.on_transfer();

