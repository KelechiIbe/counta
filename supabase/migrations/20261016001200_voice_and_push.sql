create or replace function public.save_push_subscription(p_endpoint text, p_p256dh text, p_auth text, p_platform text default null, p_user_agent text default null)
returns uuid
language plpgsql security definer set search_path = public, private as $$
declare v uuid;
begin
  if auth.uid() is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  if coalesce(p_endpoint, '') !~ '^https://' or coalesce(p_p256dh, '') = '' or coalesce(p_auth, '') = '' then
    raise exception 'That push subscription is incomplete.';
  end if;
  insert into push_subscriptions (user_id, endpoint, p256dh, auth, platform, user_agent)
  values (auth.uid(), p_endpoint, p_p256dh, p_auth, left(p_platform, 20), left(p_user_agent, 300))
  on conflict (endpoint) do update set user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth,
    platform = excluded.platform, user_agent = excluded.user_agent, active = true, failures = 0
  returning id into v;
  return v;
end $$;

create or replace function public.disable_push_subscription(p_endpoint text) returns void
language sql security definer set search_path = public, private as $$
  update push_subscriptions set active = false where endpoint = p_endpoint and user_id = auth.uid();
$$;

